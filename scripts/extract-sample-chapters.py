#!/usr/bin/env python3
"""Regenerate src/data/mockChapters.ts from eBible verse-per-line packs.

Browser development mode has no SQLite and no installer, so it needs a little
scripture compiled into the bundle. Rather than hand-typing verses — which is
how an unverified licence claim crept in the first time — this pulls the text
straight from the same packs the desktop build installs, whose redistribution
flag comes from the publisher's own catalog metadata.

Usage:
    python scripts/extract-sample-chapters.py

Downloads a few MB per translation on each run.
"""

from __future__ import annotations

import collections
import io
import pathlib
import sys
import urllib.request
import zipfile

# Chapters worth having on hand: a psalm, a gospel chapter, an epistle chapter.
WANTED = [("PSA", 23), ("JHN", 3), ("PHP", 4)]

# Each entry must be Redistributable=True in eBible's translations.csv.
SOURCES = [
    ("indayt", "Alkitab Yang Terbuka", "Copyright 2011-2024 YLSA-AYT (redistributable)"),
    ("eng-kjv2006", "King James Version", "public domain"),
]

# eBible diverges from USFM for eleven books. This mirrors `canonical_book_id`
# in src-tauri/src/install.rs; the two must agree or browser and desktop mode
# will disagree about where John lives.
EBIBLE_TO_USFM = {
    "SOL": "SNG", "EZE": "EZK", "JOE": "JOL", "NAH": "NAM", "MAR": "MRK",
    "JOH": "JHN", "PHI": "PHP", "JAM": "JAS", "1JO": "1JN", "2JO": "2JN",
    "3JO": "3JN",
}

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "data" / "mockChapters.ts"


# eBible answers 403 to urllib's default "Python-urllib/x.y" User-Agent, which
# reads as a scraper. Identifying the app honestly gets a normal response.
USER_AGENT = "BiblePoint/0.1 (+https://github.com/bible-point)"


def fetch(translation_id: str) -> str:
    url = f"https://ebible.org/Scriptures/{translation_id}_vpl.zip"
    print(f"  downloading {url}", file=sys.stderr)
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=180) as response:
        archive = response.read()

    zf = zipfile.ZipFile(io.BytesIO(archive))
    member = next(n for n in zf.namelist() if n.endswith("_vpl.txt"))
    return zf.read(member).decode("utf-8", "replace")


def extract(body: str) -> dict[str, list[str]]:
    wanted = set(WANTED)
    found: dict[str, list[tuple[int, str]]] = collections.defaultdict(list)

    for line in body.splitlines():
        parts = line.split(" ", 2)
        if len(parts) != 3:
            continue
        raw_book, chapter_verse, text = parts
        if ":" not in chapter_verse:
            continue
        chapter_str, _, verse_str = chapter_verse.partition(":")
        try:
            chapter, verse = int(chapter_str), int(verse_str)
        except ValueError:
            continue

        book = EBIBLE_TO_USFM.get(raw_book, raw_book)
        if (book, chapter) in wanted and text.strip():
            found[f"{book}:{chapter}"].append((verse, text.strip()))

    return {key: [t for _, t in sorted(values)] for key, values in found.items()}


def escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace("'", "\\'")


def main() -> int:
    chapters: dict[str, dict[str, list[str]]] = {}
    for translation_id, title, _licence in SOURCES:
        print(f"{translation_id} ({title})", file=sys.stderr)
        chapters[translation_id] = extract(fetch(translation_id))
        counts = {k: len(v) for k, v in chapters[translation_id].items()}
        print(f"  extracted {counts}", file=sys.stderr)
        missing = [f"{b}:{c}" for b, c in WANTED if f"{b}:{c}" not in chapters[translation_id]]
        if missing:
            print(f"  ERROR: missing {missing}", file=sys.stderr)
            return 1

    header_sources = "\n".join(
        f" *   {tid:<12}{title} - {licence}" for tid, title, licence in SOURCES
    )

    lines = [
        "/**",
        " * Sample scripture used when the app runs in a browser during development.",
        " *",
        " * Extracted verbatim from the same eBible.org verse-per-line packs the desktop",
        " * build installs, so browser mode shows real text from a source whose",
        " * redistribution flag has been checked against the publisher's own catalog.",
        " *",
        header_sources,
        " *",
        " * Book codes are normalised to USFM, matching what the desktop build stores.",
        " * Only three chapters are present; the desktop build reads whole Bibles from",
        " * installed packs.",
        " *",
        " * Generated by scripts/extract-sample-chapters.py — do not edit by hand.",
        " *",
        " * Key format: `chapters[translationId]['BOOK:chapter'] = [verse1, verse2, ...]`",
        " */",
        "export const MOCK_CHAPTERS: Record<string, Record<string, string[]>> = {",
    ]

    for translation_id, _title, _licence in SOURCES:
        lines.append(f"  '{translation_id}': {{")
        for book, chapter in WANTED:
            key = f"{book}:{chapter}"
            lines.append(f"    '{key}': [")
            for verse_text in chapters[translation_id][key]:
                lines.append(f"      '{escape(verse_text)}',")
            lines.append("    ],")
        lines.append("  },")

    lines += [
        "}",
        "",
        "/**",
        " * Chapters without sample text still need to render something, so the mock",
        " * source falls back to this rather than showing an empty verse list.",
        " */",
        "export const PLACEHOLDER_VERSE =",
        "  'Teks pasal ini belum tersedia di mode browser. Jalankan aplikasi desktop lalu "
        "pasang Bible pack lengkap lewat Bible Manager.'",
        "",
        "/** Chapters that actually carry sample text, surfaced as shortcuts in the UI. */",
        "export const SAMPLE_CHAPTERS = [",
    ]
    for book, chapter in WANTED:
        lines.append(f"  {{ bookId: '{book}', chapter: {chapter} }},")
    lines += ["]", ""]

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
